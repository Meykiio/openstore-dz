import { getSupabase } from "./supabase/client";

/**
 * Order export destinations.
 *
 * The URL and the signing secret are never sent to this code path for any purpose
 * other than being shown back to the owner so they can paste the secret into
 * their receiving script. Delivery itself happens in the database, in a trigger
 * that queues an async request after the order commits, so the storefront never
 * touches any of this.
 */
export type ExportTarget = {
  id: string;
  label: string;
  url: string;
  secret: string;
  enabled: boolean;
};

export type ExportLogRow = {
  id: number;
  event: string;
  status: string;
  created_at: string;
  label: string;
};

export async function listExportTargets(): Promise<ExportTarget[]> {
  const { data, error } = await getSupabase()
    .from("order_export_targets")
    .select("id, label, url, secret, enabled")
    .order("created_at", { ascending: true });
  if (error) throw new Error(error.message);
  return data ?? [];
}

export async function createExportTarget(input: { label: string; url: string }): Promise<void> {
  const { error } = await getSupabase()
    .from("order_export_targets")
    // The secret is generated by the column default, so it is never chosen by a
    // client and never travels from the browser to the database.
    .insert({ label: input.label.trim(), url: input.url.trim() });
  if (error) throw new Error(error.message);
}

export async function setExportTargetEnabled(id: string, enabled: boolean): Promise<void> {
  const { error } = await getSupabase()
    .from("order_export_targets")
    .update({ enabled })
    .eq("id", id);
  if (error) throw new Error(error.message);
}

export async function deleteExportTarget(id: string): Promise<void> {
  const { error } = await getSupabase().from("order_export_targets").delete().eq("id", id);
  if (error) throw new Error(error.message);
}

export async function listRecentExports(limit = 10): Promise<ExportLogRow[]> {
  const { data, error } = await getSupabase()
    .from("order_export_log")
    .select("id, event, status, created_at, order_export_targets(label)")
    .order("created_at", { ascending: false })
    .limit(limit);
  if (error) throw new Error(error.message);
  return (data ?? []).map((row) => {
    // The embedded relation comes back as a union because the generated types
    // cannot know it is to-one; narrow rather than casting to any.
    const related = row.order_export_targets as { label: string } | { label: string }[] | null;
    const label = Array.isArray(related) ? (related[0]?.label ?? "") : (related?.label ?? "");
    return {
      id: row.id,
      event: row.event,
      status: row.status,
      created_at: row.created_at,
      label,
    };
  });
}
